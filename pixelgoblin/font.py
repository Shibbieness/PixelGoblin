"""A 3x5 pixel font, so cards and sheets can carry text with no dependencies.

Each glyph is five rows of three bits. Lowercase is drawn as uppercase.
"""

from __future__ import annotations

from .sprite import Sprite

_G = {
    "A": "010101111101101", "B": "110101110101110", "C": "011100100100011", "D": "110101101101110",
    "E": "111100110100111", "F": "111100110100100", "G": "011100101101011", "H": "101101111101101",
    "I": "111010010010111", "J": "001001001101010", "K": "101101110101101", "L": "100100100100111",
    "M": "101111111101101", "N": "110101101101101", "O": "010101101101010", "P": "110101110100100",
    "Q": "010101101110011", "R": "110101110101101", "S": "011100010001110", "T": "111010010010010",
    "U": "101101101101111", "V": "101101101101010", "W": "101101111111101", "X": "101101010101101",
    "Y": "101101010010010", "Z": "111001010100111",
    "0": "111101101101111", "1": "010110010010111", "2": "110001010100111", "3": "110001010001110",
    "4": "101101111001001", "5": "111100110001110", "6": "011100111101111", "7": "111001010010010",
    "8": "111101111101111", "9": "111101111001110",
    " ": "000000000000000", ".": "000000000000010", ",": "000000000010100", "-": "000000111000000",
    "/": "001001010100100", ":": "000010000010000", "+": "000010111010000", "#": "101111101111101",
    "(": "010100100100010", ")": "010001001001010", "'": "010010000000000", "&": "010101010101011",
    "!": "010010010000010", "?": "110001010000010", "_": "000000000000111", "=": "000111000111000",
    "%": "101001010100101", "@": "010101111100011",
}
_G["—"] = _G["–"] = _G["-"]  # dashes in labels ("Child — Boy") draw as a hyphen


def text_width(s: str, scale: int = 1) -> int:
    return len(s) * 4 * scale - scale if s else 0


def draw(spr: Sprite, x: int, y: int, s: str, color_index: int, scale: int = 1) -> int:
    """Draw text into a sprite with palette index `color_index`. Returns the width used."""
    cx = x
    for ch in s.upper():
        g = _G.get(ch, _G["?"])
        for r in range(5):
            for c in range(3):
                if g[r * 3 + c] == "1":
                    for yy in range(scale):
                        for xx in range(scale):
                            spr.set(cx + c * scale + xx, y + r * scale + yy, color_index)
        cx += 4 * scale
    return cx - x
